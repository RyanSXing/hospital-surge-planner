"""Checksummed private artifact storage with interchangeable local/OCI adapters."""

from __future__ import annotations

import copy
import gzip
import hashlib
import json
import os
import threading
from collections import OrderedDict
from pathlib import Path

from .db import canonical, now, uid

_json_cache = OrderedDict()
_cache_lock = threading.RLock()
_cache_bytes = 0
_oci_clients = OrderedDict()
_oci_clients_lock = threading.RLock()


def _reset_oci_clients_after_fork():
    # Child workers must not inherit a parent's HTTP sessions or a held lock.
    global _oci_clients, _oci_clients_lock
    _oci_clients = OrderedDict()
    _oci_clients_lock = threading.RLock()


if hasattr(os, "register_at_fork"):
    os.register_at_fork(after_in_child=_reset_oci_clients_after_fork)


def _credential_file_signature(config):
    signatures = []
    for key in ("key_file", "security_token_file"):
        if not config.get(key):
            continue
        path = Path(config[key]).expanduser().resolve()
        try:
            stat = path.stat()
            signatures.append((str(path), stat.st_mtime_ns, stat.st_size, stat.st_ino))
        except OSError:
            signatures.append((str(path), None))
    return tuple(signatures)


def _oci_client():
    """Reuse the SDK client and its refreshing signer, never a copied token."""
    import oci

    auth = os.getenv("OCI_AUTH", "instance_principal")
    profile = os.getenv("OCI_CONFIG_PROFILE", "DEFAULT")
    config = {} if auth == "instance_principal" else oci.config.from_file(profile_name=profile)
    key = (
        os.getpid(),
        auth,
        profile,
        os.getenv("OCI_CONFIG_FILE"),
        os.getenv("OCI_REGION"),
        os.getenv("OCI_METADATA_BASE_URL"),
        hashlib.sha256(canonical(config)).hexdigest(),
        _credential_file_signature(config),
    )
    with _oci_clients_lock:
        if key in _oci_clients:
            client = _oci_clients.pop(key)
            _oci_clients[key] = client
            return client
        if auth == "instance_principal":
            # The SDK signer checks/refreshes its federation token on each
            # signed request; keeping it alive preserves that refresh behavior.
            signer = oci.auth.signers.InstancePrincipalsSecurityTokenSigner()
            client = oci.object_storage.ObjectStorageClient(config, signer=signer)
        else:
            client = oci.object_storage.ObjectStorageClient(config)
        # Failed construction is never cached. Do not close evicted clients:
        # an in-flight request may still hold an ArtifactStore using one.
        while len(_oci_clients) >= 4:
            _oci_clients.popitem(last=False)
        _oci_clients[key] = client
        return client


class ArtifactStore:
    def __init__(self):
        self.backend = os.getenv("ARTIFACT_BACKEND", "local")
        self.root = Path(os.getenv("ARTIFACT_LOCAL_DIR", "data/artifacts")).resolve()
        self.root.mkdir(parents=True, exist_ok=True)
        if self.backend == "oci":
            self.client = _oci_client()
            self.namespace = os.environ["OCI_NAMESPACE"]
            self.bucket = os.environ["OCI_ARTIFACT_BUCKET"]

    def write(self, workspace, owner, name, data: bytes, media_type="application/json"):
        # Names are generated by the service, never accepted as filesystem paths.
        key = f"{workspace}/{owner}/{uid('artifact')}/{Path(name).name}"
        checksum = hashlib.sha256(data).hexdigest()
        if self.backend == "oci":
            import base64

            md5 = base64.b64encode(hashlib.md5(data).digest()).decode()
            self.client.put_object(
                self.namespace, self.bucket, key, data, content_md5=md5, content_type=media_type
            )
        else:
            path = self.root / key
            path.parent.mkdir(parents=True, exist_ok=True)
            temporary = path.with_suffix(path.suffix + ".tmp")
            temporary.write_bytes(data)
            temporary.replace(path)
        return {
            "object_key": key,
            "sha256": checksum,
            "byte_size": len(data),
            "media_type": media_type,
            "name": Path(name).name,
            "backend": self.backend,
            "schema_version": "1.0",
            "created_at": now(),
        }

    def read(self, metadata):
        key = metadata["object_key"]
        if self.backend == "oci":
            data = self.client.get_object(self.namespace, self.bucket, key).data.content
        else:
            path = (self.root / key).resolve()
            if not path.is_relative_to(self.root):
                raise ValueError("Invalid artifact path")
            data = path.read_bytes()
        if hashlib.sha256(data).hexdigest() != metadata["sha256"]:
            raise ValueError("Artifact checksum does not match committed manifest")
        return data

    def delete(self, metadata):
        """Idempotently remove a generated private object by committed metadata."""
        key = metadata["object_key"]
        if self.backend == "oci":
            from oci.exceptions import ServiceError

            try:
                self.client.delete_object(self.namespace, self.bucket, key)
            except ServiceError as exc:
                if exc.status != 404:
                    raise
        else:
            path = (self.root / key).resolve()
            if not path.is_relative_to(self.root):
                raise ValueError("Invalid artifact path")
            path.unlink(missing_ok=True)
        global _cache_bytes
        with _cache_lock:
            for cache_key in list(_json_cache):
                if cache_key[3] == key:
                    _, size = _json_cache.pop(cache_key)
                    _cache_bytes -= size

    def put_json(self, workspace, owner, name, value):
        return self.write(
            workspace, owner, name + ".json.gz", gzip.compress(canonical(value), mtime=0), "application/gzip"
        )

    def get_json(self, metadata):
        return json.loads(gzip.decompress(self.read(metadata)))

    def get_json_cached(self, metadata, *, mutable=False):
        """Cache verified immutable artifacts; copy only when callers will edit.

        Local stat identity prevents cache hits after external modification.
        OCI keys are write-once UUID objects and keyed by committed checksum.
        The limit counts uncompressed JSON bytes and bounds entries separately.
        """
        global _cache_bytes
        signature = None
        if self.backend == "local":
            path = (self.root / metadata["object_key"]).resolve()
            if not path.is_relative_to(self.root):
                raise ValueError("Invalid artifact path")
            info = path.stat()
            signature = (info.st_mtime_ns, info.st_size)
        key = (
            self.backend,
            str(self.root),
            getattr(self, "bucket", None),
            metadata["object_key"],
            metadata["sha256"],
            signature,
        )
        with _cache_lock:
            if key in _json_cache:
                value, size = _json_cache.pop(key)
                _json_cache[key] = (value, size)
            else:
                raw = gzip.decompress(self.read(metadata))
                value, size = json.loads(raw), len(raw)
                budget = int(os.getenv("ARTIFACT_CACHE_JSON_BYTES", "536870912"))
                if size <= budget:
                    while _json_cache and (_cache_bytes + size > budget or len(_json_cache) >= 8):
                        _, (_, removed) = _json_cache.popitem(last=False)
                        _cache_bytes -= removed
                    _json_cache[key] = (value, size)
                    _cache_bytes += size
        return copy.deepcopy(value) if mutable else value
