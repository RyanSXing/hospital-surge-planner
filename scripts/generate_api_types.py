"""Generate browser command types from the authoritative Pydantic schemas.

Run: PYTHONPATH=apps/api:packages/engine .venv/bin/python scripts/generate_api_types.py
"""

from __future__ import annotations

import inspect
import json
from pathlib import Path

from pydantic import BaseModel
from surge_api import schemas


def typescript(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(typescript(value) for value in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{typescript(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        required = set(schema.get("required", []))
        fields = [
            f"{json.dumps(key)}{'' if key in required else '?'}: {typescript(value)}"
            for key, value in schema.get("properties", {}).items()
        ]
        additional = schema.get("additionalProperties")
        if additional is True:
            fields.append("[key: string]: unknown")
        elif isinstance(additional, dict):
            fields.append(f"[key: string]: {typescript(additional)}")
        return "{" + "; ".join(fields) + "}"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(kind, "unknown")


def main():
    definitions = {}
    for name, model in inspect.getmembers(schemas, inspect.isclass):
        if model is BaseModel or not issubclass(model, BaseModel):
            continue
        definition = model.model_json_schema()
        definitions.update(definition.pop("$defs", {}))
        definitions[name] = definition
    output = "// Generated by scripts/generate_api_types.py from surge_api.schemas; do not edit by hand.\n"
    output += "// Structural validation is complemented by dataset-aware server checks.\n\n"
    output += "\n\n".join(
        f"export type {name} = {typescript(value)};" for name, value in sorted(definitions.items())
    )
    target = Path(__file__).resolve().parents[1] / "apps/web/src/api-contracts.ts"
    target.write_text(output + "\n")
    print(f"Generated {len(definitions)} command/result types: {target}")


if __name__ == "__main__":
    main()
